<?php

declare(strict_types=1);

namespace App\Modules\Automation\Console\Experiments;

use App\Modules\Automation\Console\Experiments\Datasets\WorkloadGenerator;
use App\Support\Experiments\ExperimentOutput;
use Illuminate\Console\Command;

/**
 * `php artisan experiment:generate-workload --seed=42` writes the E1 workload
 * (docs/05-algorithms/evaluation-methodology.md §2). A dataset is never regenerated in place:
 * an existing folder is refused, a change goes to a new version.
 */
final class GenerateWorkload extends Command
{
    protected $signature = 'experiment:generate-workload {--seed=42} {--output= : Folder (default experiments/datasets/<dataset>/workload)}';

    protected $description = 'Generate the E1 assignment workload dataset';

    public function handle(WorkloadGenerator $generator): int
    {
        $seed = (int) $this->option('seed');
        $folder = is_string($path = $this->option('output')) && $path !== ''
            ? $path
            : config('helpdesk.experiments.path').'/datasets/'.config('helpdesk.experiments.dataset').'/workload';

        if (is_file("{$folder}/tickets.csv")) {
            $this->components->error("{$folder} already holds a workload; datasets are never regenerated in place (create a new version).");

            return self::FAILURE;
        }

        $workload = $generator->generate($seed);
        $out = new ExperimentOutput($folder);
        $out->json('agents.json', $workload['agents']);
        $out->json('categories.json', $workload['categories']);
        $out->csv('tickets.csv', $workload['tickets']);
        file_put_contents("{$folder}/README.md", $this->readme($seed, $workload));

        $this->components->info(sprintf('%d agents, %d categories, %d tickets written to %s', count($workload['agents']), count($workload['categories']), count($workload['tickets']), $folder));

        return self::SUCCESS;
    }

    /**
     * @param  array{agents: list<array{id: string, capacity: int, skills: list<string>}>, categories: list<array<string, mixed>>, tickets: list<array<string, mixed>>}  $workload
     */
    private function readme(int $seed, array $workload): string
    {
        $agents = implode("\n", array_map(
            fn (array $agent): string => "| {$agent['id']} | {$agent['capacity']} | ".implode(', ', $agent['skills']).' |',
            $workload['agents'],
        ));
        $date = now()->toDateString();

        return <<<MD
            # Workload dataset (E1)

            Generated by `php artisan experiment:generate-workload --seed={$seed}` on {$date}. Do not edit or regenerate in place; a change creates a new dataset version.

            | Item | Value |
            |---|---|
            | Seed | {$seed} |
            | Agents | {$this->count($workload['agents'])} (capacities 5–12, 2–3 skills each, every skill held by at least two agents) |
            | Categories | {$this->count($workload['categories'])} (five need one skill each, `general` needs none) |
            | Tickets | {$this->count($workload['tickets'])} |
            | Inter-arrival time | exponential, mean {$this->mean(WorkloadGenerator::MEAN_INTERARRIVAL_S)} |
            | Handling time | exponential, mean {$this->mean(WorkloadGenerator::MEAN_HANDLING_S)}, at least 60 s |

            Files: `agents.json`, `categories.json`, `tickets.csv` (`arrival_s` seconds after the start; `handling_s` seconds from assignment to resolution; `impact`, `urgency`, `tier` and `waited_h` are used by E3 for its 200 tickets).

            | Agent | Capacity | Skills |
            |---|---|---|
            {$agents}

            MD;
    }

    /** @param list<mixed> $items */
    private function count(array $items): int
    {
        return count($items);
    }

    private function mean(int $seconds): string
    {
        return $seconds >= 3600 ? round($seconds / 60).' min' : "{$seconds} s";
    }
}
